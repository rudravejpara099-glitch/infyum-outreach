// Run with: npm run extension:build. Copies the page scripts and the warm-up logic the worker already uses into the Chrome extension, so there is one copy to fix.
import { writeFileSync } from "node:fs";
import { build } from "esbuild";
import { profileFactsScript } from "@/worker/chrome-read-only-data";
import { storyLikeScript, tagPostLikeScript, warmupPageScript } from "@/worker/chrome-warmup-data";

/** Turns a script generator's string into a parameterised function by swapping known sample values for parameter names. */
function parameterise(source: string, swaps: [string, string][]): string {
  let out = source;
  for (const [text, param] of swaps) {
    if (!out.includes(text)) throw new Error(`A page script no longer contains the expected marker ${text}.`);
    out = out.split(text).join(param);
  }
  return out;
}

const facts = parameterise(profileFactsScript("a"), [[JSON.stringify("/a/"), "argTarget"]]);
const warmup = parameterise(warmupPageScript("https://www.instagram.com/p/SENTINELPOST/", "SentinelOwner", "SENTINELCOMMENT"), [
  [JSON.stringify(["/p/SENTINELPOST/", "/p/SENTINELPOST/"]), "argPaths"],
  [JSON.stringify("/sentinelowner/"), "argOwner"],
  [JSON.stringify("SENTINELCOMMENT"), "argComment"],
]);
const story = parameterise(storyLikeScript("SentinelHandle"), [[JSON.stringify("/stories/sentinelhandle/"), "argStory"]]);
if (/SENTINEL/i.test(warmup + story)) throw new Error("A sample value was left in a generated page script.");

writeFileSync("extension/page-scripts.js", `// Generated by scripts/build-extension.ts. Do not edit by hand.
export const readFactsInPage = (argTarget) => (${facts})();
export const warmupInPage = (argPaths, argOwner, argComment) => (${warmup})();
export const storyLikeInPage = (argStory) => (${story})();
export const tagPostLikeInPage = ${tagPostLikeScript()};
`);

async function main() {
  await build({
    entryPoints: ["extension/src/warmup-entry.ts"], outfile: "extension/warmup.js", bundle: true, format: "esm", platform: "browser",
    target: "chrome120", alias: { "@": "." }, logLevel: "warning",
  });
  console.log("Wrote extension/page-scripts.js and extension/warmup.js");
}
main().catch((error) => { console.error(error); process.exit(1); });
