// Run with: npm run extension:build. Copies the page-reading scripts the worker already uses into the Chrome extension, so there is one copy to fix.
import { writeFileSync } from "node:fs";
import { profileFactsScript } from "@/worker/chrome-read-only-data";

const HANDLE = "a";
const source = profileFactsScript(HANDLE);
const path = JSON.stringify(`/${HANDLE}/`);
if (!source.includes(path)) throw new Error("The profile script no longer has the expected path marker.");
const body = source.split(path).join("targetPath");
writeFileSync("extension/page-scripts.js", `// Generated by scripts/build-extension.ts. Do not edit by hand.
export const readFactsInPage = (targetPath) => (${body})();
`);
console.log("Wrote extension/page-scripts.js");
